#define getRow(c,y) ((c >> ((C_CHAR_HEIGHT - y - 1) * C_CHAR_WIDTH)) & 0x1f)
#define getIndex(row,x) ((row >> (C_CHAR_WIDTH - x - 1)) & 1)
#define getValue(c,x,y) (getIndex(getRow(c,y),x)) 

